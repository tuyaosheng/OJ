// 自然数拆分：把 n 拆成若干个（至少 2 个）正整数之和，输出所有方案。
//
// 核心难点：如何避免把 "2 3" 和 "3 2" 数成两种？
// 妙招：【强制非递减】—— 规定后选的数 >= 先选的数。
//   这样 "3 2" 根本不会被生成，每种拆分有且仅有一个合法表示 => 天然不重不漏。
//
// 实现：给递归加一个参数 start，表示"这一层最小只能从 start 开始选"。
// 复杂度：方案数级别（n=30 时约 5600 种）。
#include <iostream>
using namespace std;

const int N = 35;

int path[N];        // 当前已选的数
int n;

// rest  = 还剩多少没拆
// start = 这一层最小能选的数（保证非递减，从而不重不漏）
// cnt   = 当前已经选了几个数
void dfs(int rest, int start, int cnt)
{
    if (rest == 0)                  // 拆完了，rest 减到 0
    {
        // 题目要求至少拆成 2 个数，排除掉 "n = n" 自己这一种
        if (cnt >= 2)
        {
            for (int i = 0; i < cnt; i++)
                cout << path[i] << (i == cnt - 1 ? "\n" : " ");
        }
        return;
    }

    // 这一层选一个数 v：
    //   v >= start 保证非递减（避免重复方案）
    //   v <= rest  保证不会拆超
    // 从小到大枚举 => 输出天然是字典序
    for (int v = start; v <= rest; v++)
    {
        path[cnt] = v;              // 尝试：把 v 记进方案

        // 递归：剩余量减少 v；下一层最小仍可从 v 开始（允许重复用同一个数，如 1 1 1）
        // ★ 注意传的是 v 而不是 v+1 —— 传 v+1 会变成"每个数只能用一次"，那是另一类问题
        dfs(rest - v, v, cnt + 1);

        // 这里【不需要】显式撤销：
        // 状态全靠参数（rest/start/cnt）传递，每层独立，返回时自动恢复；
        // path[cnt] 会在下一轮循环被直接覆盖，不会污染。
        // 对比全排列：那里用了全局的 used[] 数组，就必须手动 used[v] = false。
    }
}

int main()
{
    cin >> n;

    dfs(n, 1, 0);       // 要拆 n，最小从 1 开始选，当前已选 0 个

    return 0;
}
