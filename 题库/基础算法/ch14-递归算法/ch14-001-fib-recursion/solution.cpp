// 递归求斐波那契 —— 兼学【记忆化搜索】
//
// 朴素递归 fib(n) = fib(n-1) + fib(n-2) 看似优雅，实则致命：
//   同一个子问题被反复计算（fib(5) 的调用树里，fib(2) 被算了 3 次），
//   复杂度高达 O(2^n)。n=90 时约 2^90 次调用，永远算不完。
//
// 解药：记忆化 —— 算过的结果存进 memo 数组，下次直接查表。
//   每个 fib(i) 最多真正计算一次 => 复杂度骤降到 O(n)。
//
// 记忆化是"递归"通往"动态规划"的桥梁：用递归的写法，达到递推的效率。
#include <iostream>
using namespace std;

const int N = 95;

// memo[i] 存 F(i) 的计算结果；-1 表示"还没算过"
// 用 -1 而不是 0 来标记，是更严谨的习惯（万一某个答案本身就是 0 呢）
long long memo[N];

long long fib(int n)
{
    // 递归边界：F(1) = F(2) = 1。没有边界，递归会无限往下掉
    if (n <= 2) return 1;

    // ★ 查表：如果算过了，直接返回，不再往下递归
    // 这一行就是记忆化的全部精髓，它把指数级砍成了线性级
    if (memo[n] != -1) return memo[n];

    // 没算过，才真正递归计算，并把结果【存起来】
    memo[n] = fib(n - 1) + fib(n - 2);

    return memo[n];
}

int main()
{
    int n;
    cin >> n;

    // 初始化为 -1，表示所有位置都"还没算过"
    for (int i = 0; i < N; i++)
        memo[i] = -1;

    // F(90) ≈ 2.9e18，接近 long long 上限（9.2e18），刚好装得下。
    // 用 int 的话 F(47) 就溢出了。
    cout << fib(n) << "\n";

    return 0;
}
