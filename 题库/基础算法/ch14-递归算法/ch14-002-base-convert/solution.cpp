// 十进制转任意进制（递归版）
//
// 进制转换靠"不断除以 k、取余数"，但余数是【从低位到高位】产生的，
// 而输出要【从高位到低位】—— 顺序正好相反。
//
// 递归的妙用：把输出语句放在【递归调用之后】，输出就会在"返回的路上"执行，
// 而返回顺序恰好与调用顺序相反 —— 于是顺序自动反转过来了，无需数组！
//
// 口诀：想正序输出，cout 放递归【前】；想倒序输出，cout 放递归【后】。
#include <iostream>
using namespace std;

// 把一个数位（0~15）转成对应字符
char digitChar(int r)
{
    if (r < 10)
        return '0' + r;             // 0~9  -> 字符 '0'~'9'
    else
        return 'A' + (r - 10);      // 10~15 -> 字符 'A'~'F'
}

void convert(long long n, int k)
{
    if (n == 0) return;             // 递归边界：除到 0 就收工

    convert(n / k, k);              // ★ 先递归处理【更高位】（此时还没输出任何字符）

    cout << digitChar(n % k);       // ★ 回来时才输出【当前这一位】
    // 因为输出在递归之后，它发生在"返回途中"，
    // 于是最高位最先被打印出来 —— 顺序自动倒过来了
}

int main()
{
    long long n;
    int k;
    cin >> n >> k;

    // 特判 n = 0：递归边界是 n==0 直接返回，什么也不会输出！
    // 所以必须单独处理，否则会输出空行。这是本题最容易漏的坑。
    if (n == 0)
    {
        cout << 0 << "\n";
        return 0;
    }

    convert(n, k);
    cout << "\n";

    return 0;
}
