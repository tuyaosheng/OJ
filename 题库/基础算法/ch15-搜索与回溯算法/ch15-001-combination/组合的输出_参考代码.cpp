#include <bits/stdc++.h>
using namespace std;
// 不用万能头时，需要单独引入：
//   <iostream> —— cin / cout
//
// 组合的输出：从 1~n 中取 r 个，输出所有组合（不考虑顺序）。
//
// 组合 vs 排列：组合【不看顺序】，"1 2 3" 和 "3 2 1" 是同一个。
// 避免重复的招数（和"自然数拆分"一模一样）：
//   【强制递增】—— 后选的数必须严格大于先选的数。
//   于是 "3 2 1" 根本不会被生成，每个组合只有一个合法表示 => 不重不漏。
//
// 实现：加 start 参数，表示"这一层最小能选的数"，递归时传 v+1（严格递增）。
// 复杂度：O(C(n,r) * r)。

const int N = 25;

int path[N];        // path[i] = 第 i 个选的数
int n, r;

// pos   = 当前要选第几个数（1 ~ r）
// start = 这一层最小能选的数（保证递增，从而不重不漏）
void dfs(int pos, int start)
{
    // 边界：已经选够 r 个了，输出这个组合
    if (pos > r)
    {
        for (int i = 1; i <= r; i++)
            cout << path[i] << (i == r ? "\n" : " ");
        return;
    }

    // 从 start 开始枚举（保证比上一个选的数大）
    // 从小到大枚举 => 输出天然是字典序
    for (int v = start; v <= n; v++)
    {
        path[pos] = v;          // 选择：第 pos 个数选 v

        // 递归：下一个数最小从 v+1 开始
        // ★ 传 v+1（不是 v）=> 严格递增 => 每个数只能选一次（组合的要求）
        //   对比"自然数拆分"传的是 v，那里允许重复选同一个数
        dfs(pos + 1, v + 1);

        // 状态全靠参数传递（pos、start），每层独立，无需显式撤销
    }
}

int main()
{
    cin >> n >> r;

    dfs(1, 1);      // 从第 1 个数开始选，最小可选 1

    return 0;
}
