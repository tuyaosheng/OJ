// 数字三角形：从顶走到底，每步只能走到下一行相邻的两个格子之一，求最大路径和。
//
// 暴力枚举所有路径是 2^(n-1) 条，n=1000 时天文数字，必须递推。
//
// 这里用【从下往上】递推，比从上往下更简洁（不必处理"最左/最右没有来源"的边界）：
//   设 f[i][j] = 从格子 (i,j) 出发、走到【底部】的最大路径和。
//   站在 (i,j) 上，下一步只能走到 (i+1,j) 或 (i+1,j+1)，挑大的那个：
//     f[i][j] = a[i][j] + max(f[i+1][j], f[i+1][j+1])
//   边界：最后一行哪儿也去不了，f[n][j] = a[n][j]。
//   答案：f[1][1]（从顶点出发走到底的最大和）。
//
// 复杂度：O(n^2)，n=1000 约 50 万个格子。
#include <iostream>
#include <algorithm>
using namespace std;

const int N = 1005;

int a[N][N];
int f[N][N];

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    cin >> n;

    for (int i = 1; i <= n; i++)
        for (int j = 1; j <= i; j++)
            cin >> a[i][j];

    // 边界：最后一行，站在哪儿就只能是哪儿的值（已经在底部了）
    for (int j = 1; j <= n; j++)
        f[n][j] = a[n][j];

    // 从倒数第二行往上推
    for (int i = n - 1; i >= 1; i--)
        for (int j = 1; j <= i; j++)
        {
            // 站在 (i,j)，下一步走正下方 (i+1,j) 或右下方 (i+1,j+1)，
            // 两条路都已经算好了，选和更大的那条接上去
            f[i][j] = a[i][j] + max(f[i + 1][j], f[i + 1][j + 1]);
        }
    // 注意：数字可能是负数，但这里不受影响 ——
    // 因为每个格子的两个来源都是【已算出的真实值】，不存在"未初始化的 0"参与比较。
    // 这正是从下往上写法的好处。

    cout << f[1][1] << "\n";

    return 0;
}
