// 出栈序列的数目（卡特兰数）
//
// 推导：盯住【数字 1 是第几个出栈的】。设 1 出栈前已有 k 个数先出栈（k = 0..n-1）。
//   1 最先入栈、在栈底，所以先它出栈的那 k 个数只能是 2..k+1。
//   于是 1 的出栈时刻把问题劈成两个独立的子问题：
//     左边：数字 2..k+1     （k 个数）    -> f[k] 种
//     右边：数字 k+2..n （n-1-k 个数）    -> f[n-1-k] 种
//   两边自由组合，相乘；再对所有 k 求和：
//     f[n] = Σ(k=0..n-1) f[k] * f[n-1-k]
// 边界：f[0] = 1（空序列也算一种）。
//
// 复杂度：O(n^2)。n = 5000 时约 1250 万次，可以接受。
#include <iostream>
using namespace std;

const int N = 5005;
const long long MOD = 1000000007;

long long f[N];     // 必须 long long：相乘时两数各近 1e9，乘积达 1e18

int main()
{
    int n;
    cin >> n;

    f[0] = 1;       // 0 个数只有"空序列"一种方案，这是递推的起点

    for (int i = 1; i <= n; i++)
    {
        f[i] = 0;

        // 枚举"数字 1 出栈前，有多少个数已经先出栈了"
        for (int k = 0; k <= i - 1; k++)
        {
            // f[k] 和 f[i-1-k] 都可能接近 1e9，乘积达 1e18，
            // long long 上限约 9.2e18，刚好装得下。用 int 必定溢出。
            f[i] = (f[i] + f[k] * f[i - 1 - k]) % MOD;
        }
    }

    cout << f[n] << "\n";

    return 0;
}
