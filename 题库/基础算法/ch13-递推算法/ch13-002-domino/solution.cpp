// 骨牌铺方格：用 1x2 骨牌铺满 2xn 棋盘，求方案数。
//
// 建模：盯住【最右边】怎么铺，只有两种情况（不重不漏）——
//   ① 最后一列【竖放】一块  -> 剩下 2x(i-1) 的棋盘 -> f[i-1] 种
//   ② 最后两列【横放】两块  -> 剩下 2x(i-2) 的棋盘 -> f[i-2] 种
//      （横放必须上下成对出现，否则会留下无法填充的空格）
//   => f[i] = f[i-1] + f[i-2]   —— 又是斐波那契！
//
// 注意：n=50 时答案约 2*10^10，超过 int 范围，必须用 long long。
// 复杂度：O(n)。
#include <iostream>
using namespace std;

const int N = 55;

long long f[N];     // 必须 long long：f[50] 约 2*10^10，int 装不下

int main()
{
    int n;
    cin >> n;

    // 边界
    f[1] = 1;       // 2x1 棋盘：只能竖放一块
    f[2] = 2;       // 2x2 棋盘：两块竖放，或两块横放

    if (n == 1) { cout << 1 << "\n"; return 0; }

    // 递推：从小到大依次推出每个 f[i]
    for (int i = 3; i <= n; i++)
        f[i] = f[i - 1] + f[i - 2];

    cout << f[n] << "\n";

    return 0;
}
