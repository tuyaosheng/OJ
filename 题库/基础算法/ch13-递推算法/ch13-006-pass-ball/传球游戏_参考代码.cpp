#include <bits/stdc++.h>
using namespace std;
// 不用万能头时，需要单独引入：
//   <iostream> —— cin / cout
//
// 传球游戏：n 人围成圆圈，球从 1 号出发，每次只能传给左右相邻的人，
//           恰好传 m 次后回到 1 号手里，求方案数。
//
// 状态（二维）：f[i][j] = 传了 i 次球后，球在 j 号手里的方案数。
// 转移：要让"传 i 次后球在 j 手里"，第 i 次传球前球必在 j 的左邻居或右邻居手里
//       => f[i][j] = f[i-1][左邻居] + f[i-1][右邻居]
// 初始：f[0][1] = 1（一次没传时，球在 1 号手里）。
// 答案：f[m][1]。
//
// 难点：环形下标 —— 1 号的左邻居是 n，n 号的右邻居是 1。
// 复杂度：O(n * m)，30 * 30 = 900。

const int N = 35;

long long f[N][N];      // f[传球次数][球在谁手里]

int main()
{
    int n, m;
    cin >> n >> m;

    // 初始状态：一次都没传，球在 1 号手里，方案数 1
    f[0][1] = 1;

    for (int i = 1; i <= m; i++)            // 传了 i 次
    {
        for (int j = 1; j <= n; j++)        // 球现在在 j 号手里
        {
            // 环形：算出 j 的左右邻居（这里用特判写法，清晰不易错）
            int leftNb  = (j == 1) ? n : j - 1;     // 1 号的左边是 n 号
            int rightNb = (j == n) ? 1 : j + 1;     // n 号的右边是 1 号

            // 球是从左邻居或右邻居传过来的，两种来源相加
            f[i][j] = f[i - 1][leftNb] + f[i - 1][rightNb];
        }
    }

    // 传了 m 次后，球回到 1 号手里
    cout << f[m][1] << "\n";

    return 0;
}
